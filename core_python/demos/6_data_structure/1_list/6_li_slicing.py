### slicing in list with variation : 

li = [10,30,40,50,60,70,80,90]

res = li[0:3]
print(res)
res = li[0:5:2]
print(res)
res = li[5:0:-2]
print(res)
res = li[:4]
print(res)
res = li[3:]
print(res)
res = li[:]
print(res)
res = li[:20]
print(res)
res = li[::]
print(res)
res = li[::-2]
print(res)